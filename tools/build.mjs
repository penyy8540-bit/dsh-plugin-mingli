// Build: lib/client.js (ModuleLoader wrapper), lib/index.js (host), preview/app.js + preview/index.html
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const id = pkg.name;
const write = (rel, text) => {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return text.length;
};

// ---- 1) client bundle ------------------------------------------------------
const client = await build({
  absWorkingDir: root,
  entryPoints: ['src/client-entry.jsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime'],
  loader: { '.css': 'text' },
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
});
const code = client.outputFiles[0].text;
// Guard against remote code loading. Bare URLs inside string literals (e.g. a
// library's copyright field) are fine; dynamic loading primitives with a URL are not.
const remoteLoad = code.match(/(?:importScripts|fetch|Worker|EventSource|import)\s*\(\s*["'`]https?:\/\//g);
if (remoteLoad) {
  throw new Error(`client bundle contains remote loading calls: ${remoteLoad.slice(0, 5)}`);
}
const urls = [...new Set(code.match(/https?:\/\/(?!www\.w3\.org)[^\s"'`)]+/g) || [])];
if (urls.length) console.warn(`[build] note: ${urls.length} bare URL string(s) in bundle (not loaded): ${urls.slice(0, 4).join(', ')}`);
const wrapped =
  `// Generated by tools/build.mjs — local plugin, no remote code.\n` +
  `window.__ModuleLoader__.load({id:${JSON.stringify(id)},factory:function(require){\n` +
  `var module={exports:{}};var exports=module.exports;\n` +
  code +
  `\nvar __plugin = module.exports && module.exports.default ? module.exports.default : module.exports;\n` +
  `return typeof __plugin === 'function' ? __plugin() : __plugin;\n}});\n`;
const clientBytes = write('lib/client.js', wrapped);

// ---- 2) host entry (plain ESM, no bundling needed yet) --------------------
const hostSrc = path.join(root, 'src/host/index.js');
const host = fs.existsSync(hostSrc)
  ? fs.readFileSync(hostSrc, 'utf8')
  : "export const name = 'mingli';\nexport function apply() {}\n";
const hostBytes = write('lib/index.js', host);

// ---- 3) preview bundle (react bundled, for screenshots/offline) -----------
await build({
  absWorkingDir: root,
  entryPoints: ['src/preview-entry.jsx'],
  bundle: true,
  outfile: 'preview/app.js',
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  loader: { '.css': 'text' },
  minify: false,
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
});
const previewHtml = fs.readFileSync(path.join(root, 'src/preview.html'), 'utf8')
  .replaceAll('__VERSION__', pkg.version)
  .replaceAll('__ID__', id);
write('preview/index.html', previewHtml);

// ---- 4) module-loader harness (runs the PRODUCTION client bundle offline) --
await build({
  absWorkingDir: root,
  entryPoints: ['src/harness-globals.js'],
  bundle: true,
  outfile: 'preview/harness-lib.js',
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
});
write('preview/harness.html', fs.readFileSync(path.join(root, 'src/harness.html'), 'utf8'));

console.log(`[build] client.js ${(clientBytes / 1024).toFixed(1)} KB · index.js ${hostBytes} B · preview + harness ready`);
